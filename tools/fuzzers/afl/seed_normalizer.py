"""
AFL++ Seed Normalizer

PLC semantic normalization for AFL++ binary outputs.

Implements physical layer filtering with IEC 61131-3 type compliance
and wrap-around overflow behavior simulation.

Migrated from: baselines/afl/generator.py (SeedNormalizer class)
"""

import re
from typing import Dict, Any, List


class SeedNormalizer:
    """
PLC semantic normalizer.

Real semantic normalization: Simulate PLC physical bit-width overflow behavior (Wrap-around).

Function:
- Handle binary garbled data generated by AFL++
- Brute force extract digit sequence
- Apply IEC type overflow behavior
- Maintain temporal continuity

Migrated from: baselines/afl/generator.py:SeedNormalizer
    """

    def __init__(self, schema_dict: Dict[str, Any]):
        """
        Initialize the normalizer with schema information.

        Args:
            schema_dict: Input schema dictionary containing:
                - column_count: Number of columns
                - columns: List of column names
                - metadata: IEC type mapping for each column
        """
        self.column_count = schema_dict["column_count"]
        self.columns = schema_dict["columns"]
        self.metadata = schema_dict["metadata"]
        self.column_types = [
            self.metadata[col]["iec_type"]
            for col in self.columns
        ]

    def _normalize_value(self, val: Any, iec_type: str) -> int:
        """
True semantic normalization: Simulating the wrap-around behavior of PLC physical bit width.

        Args:
            val: The value to normalize
            iec_type: The IEC 61131-3 type

        Returns:
            Normalized integer value within the type's valid range
        """
        from config.constants import IEC_TYPE_LIMITS

        limit = IEC_TYPE_LIMITS.get(iec_type, IEC_TYPE_LIMITS["INT"])
        try:
            num_val = float(val)

            # 1. BOOL mapping: non-zero means TRUE (1)
            if iec_type == "BOOL":
                return 1 if int(num_val) != 0 else 0

            # 2. Integer mapping: Simulate 8/16/32-bit two's complement overflow (Modulo-based)
            if limit["type"] == int:
                min_v, max_v = limit["min"], limit["max"]
                mod_range = max_v - min_v + 1
                # Perform modulo operation mapping, projecting C's large integer onto the PLC physical bit width space
                wrapped_val = (int(num_val) - min_v) % mod_range + min_v
                return int(wrapped_val)

            # 3. Floating-point/Others: Perform boundary clipping
            return max(limit["min"], min(limit["max"], num_val))
        except (ValueError, TypeError, OverflowError):
            # Returns default value 0 when numeric conversion fails
            return 0

    def normalize(
        self,
        raw_content: str,
        max_cycles: int = 999
    ) -> str:
        """
Robust normalization: brute-force extraction of digit sequences, ignoring binary garbage generated by AFL.

        Args:
            raw_content: Raw content from AFL++ (may contain binary garbage)
max_cycles: Maximum number of cycles to output (industrial oppression)

        Returns:
            Normalized PLC-compatible input string
        """
        # 1. Preprocessing: Replace all characters that are not digits, minus signs, or decimal points with spaces
        # This can effectively handle truncated cases like "1\x002" or "10^@0".
        clean_text = re.sub(r'[^0-9\-\.\s]', ' ', raw_content)

        # 2. Extract all numeric sequences (supports integers and floats)
        tokens = re.findall(r"-?\d+\.?\d*", clean_text)

        if not tokens:
            return ""

        normalized_rows = []
        for i in range(0, len(tokens), self.column_count):
            if len(normalized_rows) >= max_cycles:
                break  # [Industrial Oppression] Cycle Truncation

            chunk = tokens[i : i + self.column_count]
            # Padding strategy: Use the semantics of the last row to fill, maintaining temporal continuity
            while len(chunk) < self.column_count:
                chunk.append(chunk[-1] if chunk else "0")

            valid_row = [
                str(self._normalize_value(v, self.column_types[idx]))
                for idx, v in enumerate(chunk)
            ]
            normalized_rows.append(" ".join(valid_row))

        return "\n".join(normalized_rows)


__all__ = ["SeedNormalizer"]
