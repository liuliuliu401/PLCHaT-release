"""
POUS.h Parser - MatIEC output parser

Parse the POUS.h file generated by MatIEC, extract POU structure information and variable declarations.
"""

import os
import re
import sys
from pathlib import Path
from typing import List, Dict, Tuple, Optional
from dataclasses import dataclass

# Safe import method
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from harness.compiler.generator import VarDecl


@dataclass
class ArrayTypeDef:
    """Array type definition"""
    type_name: str           # __DECLARE_ARRAY_TYPE name, such as __ARRAY_OF_INT_5
    base_type: str          # Basic types, such as INT
    size: int               # Array size


@dataclass
class ParsedPOUFromH:
    """POU information parsed from POUS.h"""
    pou_name_upper: str     # Uppercase name generated by MatIEC
    vars: List[VarDecl]     # All variables (in declaration order)


class POUSParserError(Exception):
    """POUS.h parse error"""
    pass


class POUSParser:
    """
POUS.h parser

# Parse the POUS.h file generated by MatIEC, extract:
- Array type definition
- POU structure variable declaration
    """

    # Match array type definition: __DECLARE_ARRAY_TYPE(__ARRAY_OF_INT_5,INT,[5])
    ARRAY_TYPE_RE = re.compile(r'__DECLARE_ARRAY_TYPE\((\w+),(\w+),\[(\d+)\]\)')

    # Match variable declaration: __DECLARE_VAR(TYPE,NAME)
    VAR_DECL_RE = re.compile(r'__DECLARE_VAR\((\w+),(\w+)\)')

    # Match struct name comment: // FUNCTION_BLOCK MULTIPUMPCTRL
    STRUCT_NAME_RE = re.compile(r'//\s*FUNCTION_BLOCK\s+(\w+)')

    # Match start of typedef struct
    STRUCT_START_RE = re.compile(r'typedef struct\s*\{')

    def parse_file(self, pous_h_path: Path) -> ParsedPOUFromH:
        """Parse POUS.h file"""
        content = pous_h_path.read_text(encoding="utf-8")
        return self.parse_content(content)

    def parse_content(self, content: str) -> ParsedPOUFromH:
        """Parse the content of POUS.h"""
        # 1. Extract array type definition
        array_types = self._extract_array_types(content)

        # 2. Find POU structure and extract variables
        pou_name, var_decls = self._extract_struct_vars(content, array_types)

        return ParsedPOUFromH(
            pou_name_upper=pou_name,
            vars=var_decls
        )

    def _extract_array_types(self, content: str) -> Dict[str, ArrayTypeDef]:
        """Extract array type definition"""
        types = {}
        for match in self.ARRAY_TYPE_RE.finditer(content):
            type_name = match.group(1)      # __ARRAY_OF_INT_5
            base_type = match.group(2)      # INT
            size = int(match.group(3))      # 5

            types[type_name] = ArrayTypeDef(
                type_name=type_name,
                base_type=base_type,
                size=size
            )

        return types

    def _extract_struct_vars(
        self,
        content: str,
        array_types: Dict[str, ArrayTypeDef]
    ) -> Tuple[str, List[VarDecl]]:
        """Extract struct variable declaration"""
        pou_name = None
        vars_list = []

        # Check if this is a FUNCTION (no typedef struct)
        function_match = re.search(r'//\s*FUNCTION\s+(\w+)', content)
        if function_match:
            # FUNCTION type - has function declaration but no struct
            return self._extract_function_vars(content, function_match.group(1), array_types)

        # Find typedef struct block (FUNCTION_BLOCK)
        struct_start = content.find("typedef struct")
        if struct_start == -1:
            raise POUSParserError("No typedef struct found in POUS.h (not a FUNCTION_BLOCK?)")

        # Find the corresponding end position
        brace_count = 0
        in_struct = False
        struct_end = -1

        for i in range(struct_start, len(content)):
            if content[i] == '{':
                brace_count = 1
                in_struct = True
            elif in_struct:
                if content[i] == '{':
                    brace_count += 1
                elif content[i] == '}':
                    brace_count -= 1
                    if brace_count == 0:
                        struct_end = i
                        break

        if struct_end == -1:
            raise POUSParserError("Unterminated struct")

        # Extract struct content
        struct_content = content[struct_start:struct_end + 1]

        # Find POU name
        name_match = self.STRUCT_NAME_RE.search(struct_content)
        if name_match:
            pou_name = name_match.group(1)

        # Find } POU_NAME; pattern (more reliable)
        closing_pattern = re.search(r'\}\s*(\w+)\s*;', content[struct_end:struct_end + 50])
        if closing_pattern:
            pou_name = closing_pattern.group(1)

        # Extract variable declaration
        for match in self.VAR_DECL_RE.finditer(struct_content):
            var_type = match.group(1)
            var_name = match.group(2)

            # Check if it is an array type
            is_array = var_type in array_types
            array_size = None
            iec_type = var_type

            if is_array:
                array_info = array_types[var_type]
                array_size = array_info.size
                iec_type = array_info.base_type

            # Skip system variables EN/ENO (first two are fixed)
            if var_name in ("EN", "ENO"):
                continue

            vars_list.append(VarDecl(
                name=var_name.lower(),          # Unify to lowercase
                pou_name=var_name,               # Keep MatIEC format (uppercase)
                iec_type=iec_type,
                direction="UNKNOWN",             # Get from ST parser later
                is_array=is_array,
                array_size=array_size
            ))

        return pou_name, vars_list

    def _extract_function_vars(
        self,
        content: str,
        pou_name: str,
        array_types: Dict[str, ArrayTypeDef]
    ) -> Tuple[str, List[VarDecl]]:
        """Extract function parameter declaration for FUNCTION type"""
        vars_list = []

        # Parse function declaration: RETURN_TYPE NAME( TYPE arg1, TYPE *arg2, ... )
        func_pattern = re.search(
            r'(\w+)\s+' + pou_name + r'\s*\((.*?)\);',
            content,
            re.DOTALL
        )

        if not func_pattern:
            # Function declaration not found, return empty list
            return pou_name, vars_list

        params_str = func_pattern.group(2)

        # Parse parameters
        # Format: TYPE name, TYPE *name (for output pointers)
        param_pattern = re.compile(r'(\w+)\s+(?:\*\s*)?(\w+)')
        for match in param_pattern.finditer(params_str):
            var_type = match.group(1)
            var_name = match.group(2)

            # Skip system variables
            if var_name in ("EN", "ENO"):
                continue

            # Check if it is an array type
            is_array = var_type in array_types
            array_size = None
            iec_type = var_type

            if is_array:
                array_info = array_types[var_type]
                array_size = array_info.size
                iec_type = array_info.base_type

            vars_list.append(VarDecl(
                name=var_name.lower(),
                pou_name=var_name,
                iec_type=iec_type,
                direction="UNKNOWN",
                is_array=is_array,
                array_size=array_size
            ))

        return pou_name, vars_list


